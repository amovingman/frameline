'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { gunzipSync } = require('node:zlib');
const { createHash } = require('node:crypto');
const { parseEffectObservation, compareEffectObservations } = require('../src/resolve-effect-observation');
const { verifyNativeRetention } = require('../phase-0/prepare-native-track-challenge');
const root = path.join(__dirname, '..');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');

test('native track-name challenge retains five UUIDs through save/reopen and binds four empty duplicate-name tracks', () => {
  const report = JSON.parse(fs.readFileSync(path.join(root, 'phase-0/native-track-challenge-live-observation.json')));
  const compressed = fs.readFileSync(path.join(root, report.resultFile));
  assert.equal(sha(compressed), report.compressedSha256);
  const raw = gunzipSync(compressed, { maxOutputLength: 20 * 1024 * 1024 });
  assert.equal(sha(raw), '15bcde8f20413bccfa0782c4e72300ed37f913313ec76568134cd06e439f3571');
  assert.equal(raw.length, report.resultBytes);
  for (const [filename, hash] of Object.entries(report.sourceHashes)) assert.equal(sha(fs.readFileSync(path.join(root, filename))), hash);
  const result = JSON.parse(raw);
  assert.equal(result.status, 'restored'); assert.equal(result.stage, 'complete');
  assert.equal(result.representedStateRestored, true); assert.equal(result.safeToApply, false);
  const states = Object.fromEntries(['before', 'challenged', 'reopened', 'restored'].map(name => [name, parseEffectObservation(JSON.stringify(result[name]))]));
  assert.equal(states.before.snapshot.timelines[0].items.length, 50);
  assert.equal(new Set(states.before.snapshot.timelines[0].tracks.map(track => track.name)).size, 1);
  assert.deepEqual(states.before, states.restored); assert.deepEqual(states.challenged, states.reopened);
  const diff = compareEffectObservations(JSON.stringify(states.before), JSON.stringify(states.challenged));
  assert.equal(diff.snapshotChanges.length, 5);
  assert(diff.snapshotChanges.every(change => change.kind === 'track-changed' && change.field === 'name'));
  assert.deepEqual(diff.propertyChanges, []); assert.deepEqual(diff.effectChanges, []); assert.deepEqual(diff.trackStateChanges, []);
  assert.equal(report.graphs.challenged.apiBindings.length, 5);
  assert.equal(report.graphs.challenged.apiBindings.filter(row => row.itemCount === 0).length, 4);
  assert.equal(new Set(report.graphs.challenged.apiBindings.map(row => row.nativeTrackId)).size, 5);
  const retention = verifyNativeRetention(report.graphs.before, report.graphs);
  assert.equal(retention.nativeTrackIdsRetainedAcrossNameChallenge, true);
  assert.equal(retention.emptyTrackChallengeBindings, 4);
  assert.equal(report.fullNativePreservationProven, false); assert.equal(report.stableTrackIdentityProven, false);
});
